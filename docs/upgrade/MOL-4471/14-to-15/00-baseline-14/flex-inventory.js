#!/usr/bin/env node
// Exact @angular/flex-layout inventory for MOL-4471 (00-baseline).
// Counts every attribute usage (static, bound [fx...], responsive suffixes) in templates plus
// FlexLayoutModule imports in TypeScript. Emits markdown to stdout and JSON to argv[2].
const fs = require('fs');
const path = require('path');

const root = process.argv[2] || 'src';
const jsonOut = process.argv[3];

const ATTR_RE = /(?:^|[\s<(\[])\[?(fx(?:Layout|LayoutGap|LayoutAlign|Flex|FlexFill|FlexOrder|FlexOffset|FlexAlign|Hide|Show)(?:\.[a-z-]+)?|ng(?:Class|Style)\.[a-z-]+)\]?(?==|[\s>\/])/g;

function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = walk(root, []).sort();
const templates = [];
const tsImports = [];
const byDirective = {};
const bySuffix = {};
let total = 0;

for (const f of files) {
  const text = fs.readFileSync(f, 'utf8');
  if (f.endsWith('.html') || (f.endsWith('.ts') && !f.endsWith('.spec.ts') && /template\s*:/.test(text))) {
    const lines = text.split('\n');
    const hits = [];
    lines.forEach((line, i) => {
      let m;
      ATTR_RE.lastIndex = 0;
      while ((m = ATTR_RE.exec(line)) !== null) {
        const attr = m[1];
        const [base, suffix] = attr.split('.');
        byDirective[base] = (byDirective[base] || 0) + 1;
        if (suffix) bySuffix[suffix] = (bySuffix[suffix] || 0) + 1;
        hits.push({ line: i + 1, attr, base, suffix: suffix || null, src: line.trim().slice(0, 160) });
      }
    });
    if (hits.length) {
      templates.push({ file: f, count: hits.length, hits });
      total += hits.length;
    }
  }
  if (f.endsWith('.ts') && /FlexLayoutModule/.test(text)) {
    const lines = text.split('\n');
    lines.forEach((line, i) => {
      if (/FlexLayoutModule/.test(line)) tsImports.push({ file: f, line: i + 1, src: line.trim() });
    });
  }
}

const responsive = templates.reduce((n, t) => n + t.hits.filter(h => h.suffix).length, 0);
const result = { root, totalUsages: total, templates: templates.length, responsiveUsages: responsive, byDirective, bySuffix, tsImportLines: tsImports, files: templates };
if (jsonOut) fs.writeFileSync(jsonOut, JSON.stringify(result, null, 2) + '\n');

const md = [];
md.push('# @angular/flex-layout inventory (Angular 14 baseline)');
md.push('');
md.push(`Generated by \`node docs/upgrade/MOL-4471/14-to-15/00-baseline-14/flex-inventory.js src\` against \`${root}\`.`);
md.push('');
md.push(`- Templates with flex-layout usage: **${templates.length}**`);
md.push(`- Total attribute usages: **${total}** (of which responsive-suffixed: **${responsive}**)`);
md.push(`- \`FlexLayoutModule\` references in TypeScript: **${tsImports.length}** (${new Set(tsImports.map(t => t.file)).size} files)`);
md.push('');
md.push('## By directive');
md.push('');
md.push('| Directive | Count |');
md.push('|---|---|');
Object.entries(byDirective).sort((a, b) => b[1] - a[1]).forEach(([k, v]) => md.push(`| \`${k}\` | ${v} |`));
md.push('');
md.push('## By responsive suffix');
md.push('');
md.push('| Suffix | Count |');
md.push('|---|---|');
Object.entries(bySuffix).sort((a, b) => b[1] - a[1]).forEach(([k, v]) => md.push(`| \`.${k}\` | ${v} |`));
md.push('');
md.push('## FlexLayoutModule references');
md.push('');
tsImports.forEach(t => md.push(`- \`${t.file}:${t.line}\` \`${t.src}\``));
md.push('');
md.push('## Per template');
md.push('');
md.push('| # | Template | Usages | Responsive |');
md.push('|---|---|---|---|');
templates.forEach((t, i) => md.push(`| ${i + 1} | \`${t.file}\` | ${t.count} | ${t.hits.filter(h => h.suffix).length} |`));
md.push('');
md.push('## Every usage');
md.push('');
templates.forEach(t => {
  md.push(`### \`${t.file}\` (${t.count})`);
  md.push('');
  t.hits.forEach(h => md.push(`- L${h.line} \`${h.attr}\` — \`${h.src.replace(/`/g, "'")}\``));
  md.push('');
});
process.stdout.write(md.join('\n') + '\n');
